  <h2>Current Status</h2>
  <p>
    Elotrack is no longer in existence. First of all, League of Legends is an extremely popular
    game, there were several much more mature and popular tools such as
    <a href="https://na.op.gg/" target="_blank" rel="noopener noreferrer">op.gg</a> and
    <a href="https://www.leaguespy.net/" target="_blank" rel="noopener noreferrer">LeagueSpy</a> that
    already filled the niche that this tool provided. As a result, this tool recieved basically zero
    attention or interest when I shared it, making my desire to work on and maintain it much
    smaller. My primitive web design skills at the time with the <code>&lt;table&gt;</code>-based
    UI, terrible color scheme, non-responsive design, and general lack of finesse and style didn't
    help either. Secondly, the API endpoint that was keeping Elotrack alive was deprecated and
    finally killed off entirely, taking Elotrack with it. It was originally hosted on the
    elotrack.net domain, but it has since expired and I've not renewed it.
  </p>

