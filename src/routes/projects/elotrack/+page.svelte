  <h2>Tech Stack</h2>
  <p>
    Elotrack was built with a Ruby backend using the
    <a href="http://sinatrarb.com/" target="_blank" rel="noopener noreferrer">Sinatra</a> webserver
    framework. It used a MySQL database, some CLI scripts also written in Ruby and executed via Cron
    to generate some of the tables on the homepage and tablulate statistics, and had a frontend
    built with JQuery. Similarly to osu!track, much of the site content was generated by the Ruby
    with the resulting HTML being sent directly to the user. This was pretty much the last of my
    websites to be built in this manner; the rest were made using React and did most of their
    rendering client-side, pulling data from API endpoints.
  </p>
  <p>
    Despite not receiving any real traffic or popularity from users tracking their own accounts'
    stats, automated scripts ran periodically to track the top players in all of League of Legend's
    regions. A pretty hefty amount of data ended up being collected, which prompted me to put in the
    effort to learn how to optimize the database with proper indices and come up with a better
    schema. Many of the things I learned while working on Elotrack including how to manage a full
    database migration and better administer relational databases have proven useful on other
    projects since.
  </p>
